//! Writes `crates/only-regex/src/tables.rs` to stdout:
//!
//! ```text
//! cargo run --release --manifest-path tools/regex-tables/Cargo.toml > crates/only-regex/src/tables.rs
//! ```
//!
//! The tables are the Unicode `\w`, `\d` and `\s` classes and simple case folding exactly as
//! regex-syntax (pinned to the version in fuzz/Cargo.lock) builds them, so the differential fuzz
//! target `regex_search` compares the engines and not two Unicode versions.

use std::collections::BTreeSet;

use regex_syntax::hir::{Class, ClassUnicode, ClassUnicodeRange, HirKind};

const VERSION: &str = "0.8.11";

fn class(pattern: &str) -> Vec<(u32, u32)> {
    let hir = regex_syntax::Parser::new().parse(pattern).unwrap();
    let HirKind::Class(Class::Unicode(c)) = hir.kind() else {
        panic!("{pattern}: not a Unicode class");
    };
    c.ranges()
        .iter()
        .map(|r| (r.start() as u32, r.end() as u32))
        .collect()
}

fn members(c: char) -> Vec<u32> {
    let mut cls = ClassUnicode::new([ClassUnicodeRange::new(c, c)]);
    cls.case_fold_simple();
    cls.ranges()
        .iter()
        .flat_map(|r| r.start() as u32..=r.end() as u32)
        .collect()
}

fn print_pairs(name: &str, doc: &[&str], r: &[(u32, u32)]) {
    for d in doc {
        println!("/// {d}");
    }
    println!("pub(crate) const {name}: &[(u32, u32)] = &[");
    for chunk in r.chunks(5) {
        let row: Vec<String> = chunk
            .iter()
            .map(|(a, b)| format!("(0x{a:x}, 0x{b:x})"))
            .collect();
        println!("    {},", row.join(", "));
    }
    println!("];");
}

fn main() {
    println!("//! Unicode tables generated by `tools/regex-tables` from regex-syntax {VERSION}; do not edit.");
    println!();
    print_pairs(
        "WORD",
        &["`\\w`: Alphabetic, marks, decimal numbers, connector punctuation, Join_Control."],
        &class(r"\w"),
    );
    println!();
    print_pairs("DIGIT", &["`\\d`: decimal numbers (Nd)."], &class(r"\d"));
    println!();
    print_pairs("SPACE", &["`\\s`: White_Space."], &class(r"\s"));
    println!();

    // Simple case folding as cycles: each character with other case variants maps to the next
    // member of its orbit (in code point order, wrapping), so following the map from any member
    // visits the whole orbit.
    let mut next: Vec<(u32, u32)> = Vec::new();
    let mut done = BTreeSet::new();
    for cp in 0..=0x10_ffffu32 {
        let Some(c) = char::from_u32(cp) else {
            continue;
        };
        if done.contains(&cp) {
            continue;
        }
        let orbit = members(c);
        if orbit.len() == 1 {
            continue;
        }
        for &m in &orbit {
            let other = members(char::from_u32(m).unwrap());
            assert_eq!(orbit, other, "case folding of {m:x} is not an equivalence");
            done.insert(m);
        }
        for (i, &m) in orbit.iter().enumerate() {
            next.push((m, orbit[(i + 1) % orbit.len()]));
        }
    }
    next.sort_unstable();
    print_pairs(
        "FOLD",
        &[
            "Simple case folding: `(c, next)` for every character with other case variants,",
            "sorted by `c`; following `next` from `c` cycles through all its variants.",
        ],
        &next,
    );
}
