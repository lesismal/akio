/// Insert length code base, copy length code base and whether the distance is implicitly the
/// last one, for each block of 64 insert-and-copy symbols (section 5).
pub(crate) const CMD_BLOCKS: [(u8, u8, bool); 11] = [
    (0, 0, true),
    (0, 8, true),
    (0, 0, false),
    (0, 8, false),
    (8, 0, false),
    (8, 8, false),
    (0, 16, false),
    (16, 0, false),
    (8, 16, false),
    (16, 8, false),
    (16, 16, false),
];

/// The insert and copy length codes of insert-and-copy symbol `sym` (0..704) and whether its
/// distance is implicitly the last one.
#[inline]
pub(crate) const fn split_command(sym: usize) -> (usize, usize, bool) {
    let (ib, cb, implicit) = CMD_BLOCKS[(sym >> 6) % 11];
    (
        ib as usize + ((sym >> 3) & 7),
        cb as usize + (sym & 7),
        implicit,
    )
}

